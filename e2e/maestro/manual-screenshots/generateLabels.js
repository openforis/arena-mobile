// Writes labels.js: the app labels (from src/localization) used by the user manual screenshot flows,
// in the language passed as argument, as regular expressions matched by Maestro.
// Usage: node generateLabels.js <lang>
const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");
const i18next = require("i18next");

const lang = process.argv[2] ?? "en";
const localizationDir = path.resolve(__dirname, "../../../src/localization");

// localization files are TypeScript: transpiled when required
require.extensions[".ts"] = (module, filename) => {
  const { outputText } = ts.transpileModule(fs.readFileSync(filename, "utf8"), {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2020,
    },
  });
  module._compile(outputText, filename);
};

const loadModule = (file) => {
  const exported = require(file);
  return exported.default ?? exported;
};

const keys = {
  aboutTitle: "common:about",
  addArea: "offlineMaps:addArea",
  addLayer: "offlineMaps:customLayers.add",
  checkUpdates: "surveys:checkUpdates",
  columns: "dataEntry:entityListColumns.button",
  connect: "home:connect",
  customMapLayers: "offlineMaps:customLayers.title",
  dontShowAgain: "whatsNew:dontShowAgain",
  downloadedAreas: "offlineMaps:tabs.areas",
  drawPolygon: "dataEntry:geo.drawPolygon",
  findClosestSamplingPoint:
    "dataEntry:closestSamplingPoint.findClosestSamplingPoint",
  getLocation: "dataEntry:coordinate.getLocation",
  goToDataEntry: "dataEntry:goToDataEntry",
  goToListOfRecords: "dataEntry:goToListOfRecords",
  importFromCloud: "surveys:importFromCloud",
  language: "settings:language.label",
  layers: "recordsMap:layers",
  listOfRecords: "dataEntry:listOfRecords",
  login: "settingsRemoteConnection:login",
  newRecord: "dataEntry:newRecord",
  noRecordsFound: "dataEntry:noRecordsFound",
  offlineMaps: "offlineMaps:title",
  options: "dataEntry:options",
  pdfMaps: "offlineMaps:tabs.pdfMaps",
  searchTaxon: "dataEntry:taxon.search",
  selectItem: "dataEntry:code.selectItem",
  selectPicture: "dataEntry:fileAttribute.selectPicture",
  sendData: "dataEntry:sendData",
  settings: "settings:title",
  showMap: "recordsMap:mapProviderChooser.show",
  startTracking: "dataEntry:positionTracking.start",
  surveys: "home:surveys",
  useSelectedItem: "dataEntry:closestSamplingPoint.useSelectedItem",
  whatsNew: "whatsNew:title",
  noEntitiesDefined: "dataEntry:noEntitiesDefined",
  newEntity: "common:newItemWithParam",
  radar: "dataEntry:coordinate.viewModeRadar",
  selectAnItem: "common:selectAnItem",
  true: "common:true",
  yes: "common:yes",
  freeMapLayers: "settings:mapProvider.options.freeLayers",
};

const escapeRegExp = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const main = async () => {
  const resources = {};
  for (const lng of new Set(["en", lang])) {
    resources[lng] = loadModule(path.join(localizationDir, lng, "index.ts"));
  }
  await i18next.init({
    lng: lang,
    fallbackLng: "en",
    resources,
    interpolation: { escapeValue: false },
  });
  const labels = {};
  for (const [name, key] of Object.entries(keys)) {
    // parameters (e.g. {{item}}) match any text
    const value = i18next.t(key, { item: "@@" });
    if (value === key.split(":")[1])
      throw new Error(`Missing translation: ${key}`);
    labels[name] = escapeRegExp(value).replaceAll("@@", ".*");
  }
  const out = path.join(__dirname, "labels.js");
  fs.writeFileSync(
    out,
    `// generated by generateLabels.js (${lang})\noutput.lang = ${JSON.stringify(lang)};\noutput.t = ${JSON.stringify(labels, null, 2)};\n`,
  );
  console.log(`Labels (${lang}) written to ${out}`);
};

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
